#!/usr/bin/env bash
# Build agy/, the Antigravity CLI (agy) version of the Noctia plugin, from the Claude Code sources.
# Usage: bash scripts/build-agy.sh   (rebuilds agy/ from scratch, deterministic)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/agy"
AGY_ROOT='${PLUGIN_ROOT:-$HOME/.gemini/antigravity-cli/plugins/noctia}'

# check_root: refuse to run outside the Noctia repo.
check_root() {
  [ -f "$ROOT/.claude-plugin/plugin.json" ] && [ -d "$ROOT/agents" ] && [ -d "$ROOT/skills" ] \
    || { echo "build-agy: Noctia repo root not detected." >&2; exit 1; }
}

# adapt_commands: stdin to stdout, turn Claude slash commands into agy ones.
adapt_commands() {
  sed -E \
    -e 's#`/noctia:([a-z-]+) \$ARGUMENTS`#`/\1` followed by the text the user typed after the command#g' \
    -e 's#/noctia:git (locked|ask|auto)#set-git-mode.sh \1 (run by the user in a terminal)#g' \
    -e 's#/noctia:#/#g'
}

# adapt: stdin to stdout, replace the Claude-specific words of a rule, agent or skill text.
adapt() {
  sed -E \
    -e 's#^The `UserPromptSubmit` hook.*#The mode cannot be changed from the chat. The user runs `bash "${CLAUDE_PLUGIN_ROOT}/hooks/scripts/set-git-mode.sh" <mode>` in their own terminal. Do not run it with a mode, the guard denies it.#' \
    -e 's#/[^ `"]*\.claude/plugins/cache/noctia-plugins/noctia/[^/ `"]+#${CLAUDE_PLUGIN_ROOT}#g' \
    -e 's#\$\{?CLAUDE_PLUGIN_ROOT\}?#'"${AGY_ROOT//#/\\#}"'#g' \
    -e 's#Co-Authored-By: Claude <noreply@anthropic.com>#Co-Authored-By: Gemini <noreply@google.com>#' \
    -e 's#Runs on (Opus|Sonnet)#Runs on the pro model#g' \
    -e 's#Runs on Haiku#Runs on the flash model#g' \
    -e 's#\bTodoWrite\b#the task list#g' \
    -e 's#Claude Code#Antigravity CLI#g' \
    -e 's#\bClaude\b#the agent#g' \
    -e 's#\b(Opus|Sonnet)\b#pro#g' \
    -e 's#\bHaiku\b#flash#g' \
    | adapt_commands
}

# fm_value FILE KEY: print the value of KEY in the frontmatter of FILE.
fm_value() {
  awk -v k="$2" 'NR==1&&$0!="---"{exit} NR>1&&$0=="---"{exit} index($0,k": ")==1{print substr($0,length(k)+3); exit}' "$1"
}

# body FILE: print FILE without its frontmatter.
body() {
  awk 'c>=2{print; next} $0=="---"{c++}' "$1"
}

# model_for CLAUDE_MODEL: print the agy model name.
model_for() {
  case "$1" in opus|sonnet) echo pro ;; haiku) echo flash ;; *) echo inherit ;; esac
}

# write_plugin_json: write agy/plugin.json (name and description only).
write_plugin_json() {
  jq -n --arg d "$(jq -r .description "$ROOT/.claude-plugin/plugin.json" | sed 's/Opus chief, orchestrator and pentester; Sonnet developer; Haiku tester/pro-model chief, orchestrator, pentester and developer; flash-model tester/' | adapt)" \
    '{"$schema":"https://antigravity.google/schemas/v1/plugin.json", name:"noctia", description:$d}' > "$OUT/plugin.json"
}

# write_readme: write agy/README.md.
write_readme() {
  cat > "$OUT/README.md" <<'EOT'
Generated by scripts/build-agy.sh. Do not edit.

Install: from the repo root, run `bash scripts/install-agy.sh` (needs bash and jq).
EOT
}

# write_rules: write agy/rules/core.md as an always-on rule.
write_rules() {
  mkdir -p "$OUT/rules"
  { printf -- '---\ntrigger: always_on\ndescription: Noctia rules\n---\n'; adapt < "$ROOT/rules/core.md"; } > "$OUT/rules/core.md"
}

# write_agent FILE: write one agy agent.
write_agent() {
  local name main=false sub=true
  name=$(fm_value "$1" name)
  [ "$name" = chief ] && { main=true; sub=false; }
  mkdir -p "$OUT/agents"
  {
    printf -- '---\nname: %s\ndescription: %s\nmodel: %s\nsubagent: %s\nmainAgent: %s\n---\n' \
      "$name" "$(fm_value "$1" description | adapt)" "$(model_for "$(fm_value "$1" model)")" "$sub" "$main"
    body "$1" | adapt
  } > "$OUT/agents/$name.md"
}

# write_skill DIR: write one agy skill and copy its other files.
write_skill() {
  local name dest
  name=$(basename "$1")
  dest="$OUT/skills/$name"
  mkdir -p "$dest"
  cp -pR "$1/." "$dest/"
  {
    printf -- '---\nname: %s\ndescription: %s\n---\n' "$name" "$(fm_value "$1/SKILL.md" description | adapt)"
    body "$1/SKILL.md" | adapt
  } > "$dest/SKILL.md"
}

# write_hook_scripts: copy the hook scripts; the always-on rule replaces the rules injection of session-start.
write_hook_scripts() {
  local f
  mkdir -p "$OUT/hooks/scripts"
  cp -p "$ROOT"/hooks/scripts/*.sh "$OUT/hooks/scripts/"
  for f in "$OUT"/hooks/scripts/*.sh; do
    [ "$(basename "$f")" = agy-hook.sh ] && continue
    sed -E 's#Ask the user to type /noctia:git <locked\|ask\|auto> in the chat\. In agy the user runs this in their terminal:#Ask the user to run this in their terminal:#' "$f" | adapt_commands > "$f.tmp" && cat "$f.tmp" > "$f" && rm "$f.tmp"
  done
  sed -i 's#^  cat "\$PLUGIN_ROOT/rules/core.md"$#  :#' "$OUT/hooks/scripts/session-start.sh"
}

# write_hooks_json: write agy/hooks.json (git guard, secret guard, session start).
write_hooks_json() {
  jq -n --arg r "$AGY_ROOT" '
    def cmd($n): "bash \"" + $r + "/hooks/scripts/agy-hook.sh\" " + $n;
    def pre($n): {PreToolUse: [{matcher: ".*", hooks: [{type: "command", command: cmd($n), timeout: 10}]}]};
    {"noctia-guard-git": pre("guard-git"),
     "noctia-guard-secrets": pre("guard-secrets"),
     "noctia-session-start": {SessionStart: [{type: "command", command: cmd("session-start SessionStart"), timeout: 10}]}}
  ' > "$OUT/hooks.json"
}

# write_statusline: copy the status line script (keep the exec bit).
write_statusline() {
  mkdir -p "$OUT/statusline"
  cp -p "$ROOT"/statusline/*.sh "$OUT/statusline/"
}

main() {
  local f d
  check_root
  rm -rf "$OUT"
  mkdir -p "$OUT"
  write_plugin_json
  write_readme
  write_rules
  for f in "$ROOT"/agents/*.md; do write_agent "$f"; done
  for d in "$ROOT"/skills/*/; do write_skill "${d%/}"; done
  write_hook_scripts
  write_hooks_json
  write_statusline
  echo "agy/ built."
}

main
